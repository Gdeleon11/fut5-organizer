-- =============================================================================
-- Migration: tournament playoff metadata columns
--
-- Why: src/tournamentEngine.js (generateFixtures) writes `is_playoff`,
--      `playoff_label` and `is_final` for the formats cuadrangular,
--      league_playoffs and playoffs_only, but public.tournament_matches never had
--      those columns (see supabase/tournaments-migration.sql). PostgREST rejects the
--      insert ("Could not find the 'is_playoff' column ... in the schema cache"),
--      so "Generar calendario" only worked for the plain `league` format.
--
-- What: additive and idempotent. No table, row, policy or relation is dropped or
--       changed. Existing rows get is_playoff = false / is_final = false, which is
--       exactly what the engine writes for league fixtures (it omits the keys).
--
-- Types follow the engine:
--   is_playoff    boolean, set true on every playoff fixture  → NOT NULL DEFAULT false
--   is_final      boolean, set true on the cuadrangular final → NOT NULL DEFAULT false
--   playoff_label text, "Semifinal 1" / "Semifinal 2" / "Final" (league_playoffs only)
--                 → nullable, no default
--
-- RLS: unchanged. New columns inherit the existing table policies
--      (tournament_matches_select_member / tournament_matches_manage_admin).
-- Rollback (if ever needed): ALTER TABLE ... DROP COLUMN IF EXISTS for the three
--      columns; the app then falls back to "league only" calendar generation.
-- =============================================================================

BEGIN;

ALTER TABLE public.tournament_matches
  ADD COLUMN IF NOT EXISTS is_playoff boolean NOT NULL DEFAULT false;

ALTER TABLE public.tournament_matches
  ADD COLUMN IF NOT EXISTS is_final boolean NOT NULL DEFAULT false;

ALTER TABLE public.tournament_matches
  ADD COLUMN IF NOT EXISTS playoff_label text;

COMMENT ON COLUMN public.tournament_matches.is_playoff IS 'True for elimination-stage fixtures generated by tournamentEngine (league_playoffs, playoffs_only).';
COMMENT ON COLUMN public.tournament_matches.is_final IS 'True for the cuadrangular final generated by tournamentEngine.';
COMMENT ON COLUMN public.tournament_matches.playoff_label IS 'Display label for playoff fixtures, e.g. Semifinal 1, Final.';

COMMIT;

-- Make PostgREST pick up the new columns immediately.
NOTIFY pgrst, 'reload schema';
